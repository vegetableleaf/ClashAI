"""Generate curve-v1 Markdown tables: python aggregate_v1.py RUNS_DIR OUT.md."""

import argparse
import json
from pathlib import Path


POINTS = [('m2', 'cv1_m2_s0'), ('m5', 'cv1_m5_s0'),
          ('m10 s0 (base_pre)', 'base_pre'), ('m10 s1', 'cv1_m10_s1'),
          ('m20', 'cv1_m20_s0')]
RUNS = ['base_pre', 'base_ice', 'cv1_m2_s0', 'cv1_m5_s0',
        'cv1_m20_s0', 'cv1_m10_s1', 'clxiii', 'v0_m10']
V0 = {'m2': 5.3494, 'm5': 5.2780, 'm10': 5.2467, 'm20': 5.2342}


def get(obj, *keys):
    for key in keys:
        if not isinstance(obj, dict):
            return None
        obj = obj.get(key)
    return obj


def fmt(value, digits=4):
    return 'n/a' if value is None else f'{value:.{digits}f}'


def difference(a, b):
    return None if a is None or b is None else a - b


def scaled(value, divisor):
    return None if value is None else value / divisor


def cell(value):
    return 'n/a' if value is None else str(value).replace('|', '\\|').replace('\n', ' ')


def table(lines, title, headers, rows):
    lines.extend(['', '## ' + title, '', '| ' + ' | '.join(headers) + ' |',
                  '| ' + ' | '.join(['---'] * len(headers)) + ' |'])
    for row in rows:
        lines.append('| ' + ' | '.join(cell(v) for v in row) + ' |')


def generate(root):
    data, finals, missing = {}, {}, []
    for name in RUNS:
        rel = Path(name + '_eval.json') if name in ('clxiii', 'v0_m10') else Path(name) / 'eval.json'
        path = root / rel
        if path.is_file():
            data[name] = json.loads(path.read_text(encoding='utf-8-sig'))
        else:
            data[name] = {}
            missing.append(rel.as_posix())
        if name in ('clxiii', 'v0_m10'):
            continue
        rel = Path(name) / 'train.out'
        path = root / rel
        finals[name] = {}
        if not path.is_file():
            missing.append(rel.as_posix())
            continue
        for line in path.read_text(encoding='utf-8-sig').splitlines():
            try:
                record = json.loads(line)
            except json.JSONDecodeError:
                continue
            if isinstance(record, dict) and 'FINAL' in record:
                finals[name] = record
        if not finals[name]:
            missing.append(rel.as_posix() + ' (FINAL record missing)')

    def total(name, group):
        return get(data[name], group, 'nll_total')

    def m10(group):
        # Never substitute seed 1 for a missing base_pre/seed 0.
        a, b = total('base_pre', group), total('cv1_m10_s1', group)
        both = (root / 'base_pre/eval.json').is_file() and (root / 'cv1_m10_s1/eval.json').is_file()
        if both:
            return (None if a is None or b is None else (a + b) / 2), 'mean of 2 seeds'
        return a, ('seed 0 only' if (root / 'base_pre/eval.json').is_file() else 'n/a')

    lines = ['Generated by aggregate_v1.py from RUNS_DIR; labels: (a) measured',
             '', 'RUNS_DIR: ' + str(root)]
    groups = [
        ('Table 1. Held-out NLL by model size, HF held-out (group heldout_hf)', 'heldout_hf', 'train_hf'),
        ("Table 2a. Held-out NLL by model size, v32 pro rows, curve v0's held-out (group heldout_v32)", 'heldout_v32', 'train_v32'),
        ('Table 2b. Held-out NLL by model size, icebow-deck rows (group ice_hf)', 'ice_hf', None),
    ]
    for title, group, train in groups:
        rows = []
        for label, name in POINTS:
            e = data[name]
            held, training = total(name, group), total(name, train) if train else None
            shape = f"{e['d']} x {e['layers']}" if get(e, 'd') is not None and get(e, 'layers') is not None else 'n/a'
            rows.append([label, fmt(scaled(get(e, 'n_params'), 1e6), 2), shape,
                         *[fmt(get(e, group, 'nll_' + k)) for k in ('total', 'cell', 'card', 'wait', 'gate', 'value')],
                         fmt(get(e, group, 'top1_cell_tile')), fmt(get(e, group, 'top1_card')),
                         fmt(training), fmt(difference(held, training)),
                         fmt(scaled(get(finals[name], 'seconds'), 3600), 2)])
        table(lines, title, ['point', 'params (M)', 'd x layers', 'NLL total', 'cell', 'card', 'wait', 'gate', 'value',
                            'top1 tile', 'top1 card', (train or 'train (none)') + ' total', 'gap (held-out - train)', 'FINAL hours'], rows)

    rows = []
    for group in ('heldout_hf', 'heldout_v32'):
        ten, basis = m10(group)
        noise = difference(total('base_pre', group), total('cv1_m10_s1', group))
        noise = None if noise is None else abs(noise)
        values = [total('cv1_m2_s0', group), total('cv1_m5_s0', group), ten, total('cv1_m20_s0', group)]
        for i, step in enumerate(('m2 -> m5', 'm5 -> m10', 'm10 -> m20')):
            gain = difference(values[i], values[i + 1])
            ratio = None if gain is None or noise in (None, 0) else gain / noise
            rows.append([group, step, fmt(gain), fmt(noise), fmt(ratio), basis])
    table(lines, 'Table 3. Step gains', ['group', 'step', 'gain (smaller - larger NLL)', 'seed noise (NLL unit)', 'gain/noise', 'm10 basis'], rows)
    lines.extend(['', 'Noise unit = |m10 s0 - m10 s1| for each group. Gain/noise is n/a when noise is missing or zero.'])

    rows = []
    for label, name in [('m2', 'cv1_m2_s0'), ('m5', 'cv1_m5_s0'), ('m10', 'base_pre'), ('m20', 'cv1_m20_s0')]:
        value, basis = m10('heldout_v32') if label == 'm10' else (total(name, 'heldout_v32'), 'seed 0 only' if data[name] else 'n/a')
        rows.append([label, fmt(V0[label]), fmt(value), fmt(difference(value, V0[label])), basis])
    table(lines, 'Table 4. Curve v0 vs v1 on heldout_v32', ['point', 'v0 total (SCALE.md)', 'v1 total', 'difference (v1 - v0)', 'v1 basis'], rows)
    delta = difference(total('v0_m10', 'heldout_v32'), V0['m10'])
    result = 'n/a' if delta is None else ('PASS' if abs(delta) < .002 else 'FAIL')
    lines.extend(['', 'Curve-v0 m10 re-evaluated on the mix (v0_m10_eval.json, heldout_v32): '
                  + fmt(total('v0_m10', 'heldout_v32')) + ' vs SCALE.md 5.2467; difference (re-evaluated - SCALE.md): '
                  + fmt(delta) + '; equivalence check (|diff| < 0.002): ' + result + '.'])

    groups = ('heldout_hf', 'heldout_v32', 'v3val', 'ice_hf', 'ice_v32')
    table(lines, 'Table 5. Icebow base vs CLXIII', ['model'] + [g + ' NLL total' for g in groups],
          [[name] + [fmt(total(name, g)) for g in groups] for name in ('base_pre', 'base_ice', 'clxiii', 'v0_m10')])

    rows = []
    errors = []
    for label, name in [('base_pre', 'base_pre'), ('base_ice', 'base_ice'), ('clxiii', 'clxiii'),
                        ('cv1_m2', 'cv1_m2_s0'), ('cv1_m5', 'cv1_m5_s0'), ('cv1_m20', 'cv1_m20_s0'),
                        ('cv1_m10_s1', 'cv1_m10_s1'), ('v0_m10', 'v0_m10')]:
        e = data[name]
        decide = get(e, 'latency_decide')
        rows.append([label, fmt(scaled(get(e, 'n_params'), 1e6), 2),
                     *[fmt(get(e, 'latency_ms', mode, pct + '_ms'), 1) for mode, pct in
                       [('bs1_fp32', 'p50'), ('bs1_fp32', 'p99'), ('bs1_bf16', 'p50'), ('bs1024_bf16', 'p50')]],
                     fmt(get(decide, 'eager', 'p50_ms'), 1), fmt(get(decide, 'eager', 'p99_ms'), 1),
                     get(decide, 'n_cuda_kernels'), fmt(get(decide, 'graph', 'p50_ms'), 1), fmt(get(decide, 'graph', 'p99_ms'), 1),
                     get(decide, 'graph_argmax_equal'),
                     *[get(decide, 'graph_max_abs_diff_vs_eager', k) for k in ('gate', 'card', 'cell')], get(e, 'gpu')])
        if isinstance(decide, dict):
            errors.extend(f'{label}: {key}: {cell(value)}' for key, value in decide.items() if key == 'error' or key.endswith('_error'))
    table(lines, 'Table 6. Latency on the pod GPU (batch 1)',
          ['model', 'params (M)', 'bs1 fp32 p50 ms', 'bs1 fp32 p99 ms', 'bs1 bf16 p50 ms', 'bs1024 bf16 p50 ms',
           'decide eager p50 ms', 'decide eager p99 ms', 'n_cuda_kernels', 'graph p50 ms', 'graph p99 ms',
           'graph argmax equal', 'graph max abs diff gate', 'graph max abs diff card', 'graph max abs diff cell', 'GPU name'], rows)
    if errors:
        lines.extend(['', 'Recorded latency errors:'] + ['- ' + error for error in errors])
    lines.extend(['', 'Missing inputs: ' + (', '.join(missing) if missing else 'none') + '.',
                  'Missing metric keys are shown as n/a. curve_*.jsonl files are not needed for these tables.'])
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('runs_dir', type=Path)
    parser.add_argument('out', type=Path)
    args = parser.parse_args()
    args.out.write_text(generate(args.runs_dir), encoding='utf-8')


if __name__ == '__main__':
    main()
