"""J-ALL-CARDS per-card COVERAGE table (W1, 10-20): for every card / evolution / hero form in the SIM's card table, how much
live evidence each engine metric has, and which cards need owner-played targeted battles. Writes COVERAGE.md.

  python coverage_table.py CENSUS.json STATIC.json [CENSUS_ALL.json [REPLAY_DIR]] > COVERAGE.md
CENSUS = census_metrics.py output (frame logs); STATIC = static_check.py output; CENSUS_ALL = coverage/census_cards.py over
every live log since 10-07, census_all.json (plays only; decision-only logs undercount short-lived bodies).
"""
from __future__ import annotations

from collections import Counter
import json
import math
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[5]))
from scratchpad.gauntlet.L74.parity.metrics.static_check import EVENT  # noqa: E402

N_GOAL = 30            # the owner's per-card n (fight-parity-goal: per card only with n >= 30)
PER_BATTLE = 6         # ponytail: plays of one card in one targeted 3-min battle, a cycle-deck guess; measure on the first battles


def main(census_p, static_p, all_p=None, replay_dir=None):
    census = json.loads(Path(census_p).read_text())['matches']
    static = json.loads(Path(static_p).read_text())
    allc = json.loads(Path(all_p).read_text()) if all_p else None
    ms = [m for m in census if 'plays' in m]
    ext = [m for m in ms if m.get('ext') and m['match'] >= 'live_play_20261016']
    plays, plays_ext, casts, torn, act, dep, br, inm, lv = (Counter() for _ in range(9))
    for m in ms:
        for k, v in m['plays'].items():
            plays[k.split(' ', 1)[1]] += v
        for k in {k.split(' ', 1)[1] for k in m['plays']}:
            inm[k] += 1
    for m in ext:
        for k, v in m['plays'].items():
            plays_ext[k.split(' ', 1)[1]] += v
        for k, v in m['casts'].items():
            casts[k.split(' ', 1)[1]] += v
        for r in m['tornado']:
            torn[r['victim'].split(' ', 1)[1]] += 1
        for r in m['king']:
            for a in r.get('activators') or []:
                act[a.split(' ', 1)[1]] += 1
        for k, v in m['deploy'].items():
            dep[k.split(' ', 1)[1]] += sum(v.values())
        for k, v in m['bridge'].items():
            br[k.split(' ', 1)[1]] += len(v)
    for m in ext:
        for lab, level, hp, n in m.get('levels') or []:
            if not lab.startswith('tower'):
                lv[lab.split(' ', 1)[1]] += 1
    allp = Counter()
    if allc:
        for k, v in allc['plays'].items():
            allp[k.split(' ', 1)[1]] += v
    dev = {r['card']: r for r in static['device_vs_sim'] if not r['card'].startswith('unit:')}
    live_bad = Counter(r['card'] for r in static.get('live_vs_sim', []) if not r['ok'] and not r['card'].startswith('tower'))
    sim_doc_names = list(dev)
    rows = []
    for name in sim_doc_names:
        lab = name.replace('_EV1', ' evo').replace('_hero', ' hero')
        r = dev[name]
        n = plays_ext.get(lab, 0)
        ev = any(e in name for e in EVENT)
        verdict = 'event-only' if ev else 'covered' if n >= N_GOAL else 'thin' if n >= 10 else 'NEEDS BATTLES'
        need = 0 if ev or n >= N_GOAL else math.ceil((N_GOAL - n) / PER_BATTLE)
        rows.append(dict(card=lab, all=allp.get(lab, 0), frames=plays.get(lab, 0), ext=n, matches=inm.get(lab, 0), casts=casts.get(lab, 0),
                         torn=torn.get(lab, 0), act=act.get(lab, 0), dep=dep.get(lab, 0), br=br.get(lab, 0), lv=lv.get(lab, 0),
                         static=r['status'] + (f' (live hp miss {live_bad[lab]})' if live_bad.get(lab) else ''), verdict=verdict, need=need))
    rows.sort(key=lambda r: (-r['ext'], -r['all'], r['card']))
    v = Counter(r['verdict'] for r in rows)
    print('# Per-card live evidence COVERAGE (J-ALL-CARDS; generated by coverage_table.py, W1 10-20)\n')
    print(f"Every card / evolution / hero form in the SIM card table ({len(rows)} records, device table 10-12 names). Live evidence "
          f"from the census of {len(ms)} frame-logged matches (10-15..10-20, any account) of which {len(ext)} ext logs since 10-16"
          + (f"; 'all logs' = coverage/census_cards.py over {allc['matches']} matches since 10-07" if allc else '') + ".\n")
    print(f"Verdict (ext-log plays, the J1/J5 unit; owner rule n >= {N_GOAL} per card): " + ', '.join(f'{k} {c}' for k, c in v.most_common())
          + f". Targeted battles needed (at ~{PER_BATTLE} plays of the card per battle, a guess to calibrate): {sum(r['need'] for r in rows)} card-battles "
          f"over {sum(1 for r in rows if r['need'])} cards; one battle covers up to 8 cards of one deck.\n")
    print('Columns: plays all logs (both sides) | plays in frame logs | plays in ext logs (graded) | matches with the card | J2 casts '
          '(spells) | J2 Tornado exposures as victim | J3 king-activation events with it in king reach | J5 deploy observations '
          '(bodies) | J6 river crossings (bodies) | (level, hp) triples seen | static vs device / live hp | verdict | battles\n')
    print('| card | all | frames | ext | matches | J2 casts | J2 torn | J3 act | J5 dep | J6 cross | lv | static | verdict | battles |')
    print('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|')
    for r in rows:
        print(f"| {r['card']} | {r['all']} | {r['frames']} | {r['ext']} | {r['matches']} | {r['casts']} | {r['torn']} | {r['act']} | "
              f"{r['dep']} | {r['br']} | {r['lv']} | {r['static']} | {r['verdict']} | {r['need'] or ''} |")
    # labels seen live that the table has no record for (identity gaps)
    known = {r['card'] for r in rows}
    unk = sorted({k for k in plays if k not in known})
    if unk:
        print(f"\nLive labels with no SIM table record ({len(unk)}): " + ', '.join(f'{k} ({plays[k]})' for k in unk))
    if replay_dir:
        from scratchpad.gauntlet.L74.parity.metrics import percard
        print(f"\n## Per-card replay metric values (replay_metrics.py fights over {Path(replay_dir).name}; cards with n >= 10 on a metric)\n")
        print('J2 = the card as a spell victim (end point within 0.5 tile). J5a = deploy within 3 ticks. J6 = pathing proper '
              '(river crossing lane + tick, both alive). Laptop royalesim 0.1.36; the fork numbers come from the pod job.\n')
        percard.main(replay_dir, 10)


if __name__ == '__main__':
    main(*sys.argv[1:5])
